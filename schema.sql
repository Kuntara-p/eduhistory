-- 1. ตาราง Cloud State Store สำหรับ EduHistory (ซิงค์ทุกอย่างในตารางนี้)
CREATE TABLE IF NOT EXISTS public.eduhistory_store (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. ตารางนักเรียนวิชาประวัติศาสตร์
CREATE TABLE IF NOT EXISTS public.eduhistory_students (
    id TEXT PRIMARY KEY,
    student_no INT NOT NULL,
    name TEXT NOT NULL,
    grade TEXT NOT NULL,
    room TEXT NOT NULL DEFAULT '1',
    gender TEXT,
    status TEXT NOT NULL DEFAULT 'กำลังศึกษา',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. ตารางเช็คชื่อเข้าเรียน
CREATE TABLE IF NOT EXISTS public.eduhistory_attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    student_id TEXT NOT NULL REFERENCES public.eduhistory_students(id) ON DELETE CASCADE,
    status TEXT NOT NULL CHECK (status IN ('มา', 'ลา', 'ป่วย', 'ขาด')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(date, student_id)
);

-- 4. ตารางคะแนนตัวชี้วัด ปพ.5
CREATE TABLE IF NOT EXISTS public.eduhistory_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL REFERENCES public.eduhistory_students(id) ON DELETE CASCADE,
    indicator_id TEXT NOT NULL,
    score NUMERIC(5,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(student_id, indicator_id)
);

-- 5. ตารางชิ้นงานย่อย / การบ้าน
CREATE TABLE IF NOT EXISTS public.eduhistory_sub_assignments (
    id TEXT PRIMARY KEY,
    classroom_id TEXT NOT NULL,
    indicator_id TEXT NOT NULL,
    title TEXT NOT NULL,
    max_score NUMERIC(5,2) NOT NULL DEFAULT 10,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. ตารางคะแนนงานย่อย
CREATE TABLE IF NOT EXISTS public.eduhistory_sub_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL REFERENCES public.eduhistory_students(id) ON DELETE CASCADE,
    assignment_id TEXT NOT NULL,
    score NUMERIC(5,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(student_id, assignment_id)
);

-- 7. ตารางบันทึกหลังสอน
CREATE TABLE IF NOT EXISTS public.eduhistory_lesson_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    grade_room TEXT NOT NULL,
    topic TEXT NOT NULL,
    problems TEXT,
    suggestions TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_eh_students_grade_room ON public.eduhistory_students(grade, room);
CREATE INDEX IF NOT EXISTS idx_eh_attendance_date ON public.eduhistory_attendance(date);
CREATE INDEX IF NOT EXISTS idx_eh_scores_student ON public.eduhistory_scores(student_id);
CREATE INDEX IF NOT EXISTS idx_eh_sub_assign_cls ON public.eduhistory_sub_assignments(classroom_id, indicator_id);

-- เปิดใช้งาน Row Level Security (RLS)
ALTER TABLE public.eduhistory_store ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eduhistory_students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eduhistory_attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eduhistory_scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eduhistory_sub_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eduhistory_sub_scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eduhistory_lesson_logs ENABLE ROW LEVEL SECURITY;

-- กำหนดสิทธิ์ให้ใช้งานผ่าน Anon Public Key
CREATE POLICY "Allow public all on eduhistory_store" ON public.eduhistory_store FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on eduhistory_students" ON public.eduhistory_students FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on eduhistory_attendance" ON public.eduhistory_attendance FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on eduhistory_scores" ON public.eduhistory_scores FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on eduhistory_sub_assignments" ON public.eduhistory_sub_assignments FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on eduhistory_sub_scores" ON public.eduhistory_sub_scores FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on eduhistory_lesson_logs" ON public.eduhistory_lesson_logs FOR ALL USING (true) WITH CHECK (true);

